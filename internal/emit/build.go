func Build(packageObj *semantic.PackageObj) ([]FileObj, error) {
	templateDataObj, err := buildTemplateData(packageObj)
	if err != nil {
		return nil, err
	}

	fileNameTextArr := GeneratedFileNameArr(packageObj)
	schemaLabelText := packageObj.SchemaLabel
	if schemaLabelText == "" {
		schemaLabelText = packageObj.SchemaPath
	}

	fileObjArr := make([]FileObj, 0, len(fileNameTextArr))
	for _, fileNameText := range fileNameTextArr {
		dataArr, renderErr := renderTemplateFile(fileNameText, templateDataObj)
		if renderErr != nil {
			return nil, fmt.Errorf("render generated file [%s]: %w", fileNameText, renderErr)
		}

		formattedArr, formatErr := format.Source(dataArr)
		if formatErr != nil {
			return nil, fmt.Errorf("format generated file [%s]: %w", fileNameText, formatErr)
		}

		fileObjArr = append(fileObjArr, FileObj{
			RelativePath: fileNameText,
			DataArr:      prependGeneratedHeader(formattedArr, schemaLabelText),
		})
	}

	return fileObjArr, nil
}

func prependGeneratedHeader(dataArr []byte, schemaPathText string) []byte {
	headerText := buildGeneratedHeader(schemaPathText)
	resultArr := make([]byte, 0, len(headerText)+len(dataArr))
	resultArr = append(resultArr, headerText...)
	resultArr = append(resultArr, dataArr...)
	return resultArr
}

func buildGeneratedHeader(schemaPathText string) string {
	return fmt.Sprintf(
		"// Code generated by goconfgen; DO NOT EDIT.\n// Source schema: %s\n\n",
		schemaPathText,
	)
}

func GeneratedFileNameArr(packageObj *semantic.PackageObj) []string {
	resultArr := make([]string, 0, len(cFileSpecArr))
	for _, specObj := range cFileSpecArr {
		if specObj.Predicate(packageObj) {
			resultArr = append(resultArr, specObj.NameText)
		}
	}
	return resultArr
}

func KnownGeneratedFileNameArr() []string {
	resultArr := make([]string, 0, len(cFileSpecArr)+16)
	for _, specObj := range cFileSpecArr {
		resultArr = append(resultArr, specObj.NameText)
	}
	resultArr = append(resultArr,
		"schema_gen.go",
		"field_meta_gen.go",
		"runtime_gen.go",
		"validate_gen.go",
		"flags_gen.go",
		"presets_gen.go",
		"parsers_gen.go",
		"parser_yaml_gen.go",
		"parser_json_gen.go",
		"parser_hjson_gen.go",
		"parser_cli_gen.go",
		"parse_gen.go",
		"render_gen.go",
	)
	return resultArr
}

type fileSpecObj struct {
	NameText  string
	Predicate func(*semantic.PackageObj) bool
}

var cFileSpecArr = []fileSpecObj{
	{"types_gen.go", alwaysFile},
	{"enums_gen.go", func(packageObj *semantic.PackageObj) bool { return len(packageObj.EnumObjArr) > 0 }},
	{"helpers_gen.go", alwaysFile},
	{"accessors_gen.go", alwaysFile},
	{"parse_yaml.go", func(packageObj *semantic.PackageObj) bool { return packageObj.HasYAML }},
	{"parse_json.go", func(packageObj *semantic.PackageObj) bool { return packageObj.HasJSON }},
	{"parse_hjson.go", func(packageObj *semantic.PackageObj) bool { return packageObj.HasHJSON }},
	{"render_yaml.go", func(packageObj *semantic.PackageObj) bool { return packageObj.HasYAML && packageObj.HasRender }},
	{"render_json.go", func(packageObj *semantic.PackageObj) bool { return packageObj.HasJSON && packageObj.HasRender }},
	{"render_hjson.go", func(packageObj *semantic.PackageObj) bool { return packageObj.HasHJSON && packageObj.HasRender }},
	{"cli.go", func(packageObj *semantic.PackageObj) bool { return packageObj.HasCLI }},
	{"validate.go", func(packageObj *semantic.PackageObj) bool { return packageObj.HasValidate }},
	{"presets.go", func(packageObj *semantic.PackageObj) bool { return packageObj.HasPresets }},
	{"entrypoint.go", alwaysFile},
}

func alwaysFile(packageObj *semantic.PackageObj) bool {
	return true
}

func buildTemplateData(packageObj *semantic.PackageObj) (*TemplateDataObj, error) {
	var presetObjArr []PresetTemplateObj
	var presetDataArr []byte
	if packageObj.HasPresets {
		var err error
		presetObjArr, presetDataArr, err = buildPresetBundle(packageObj)
		if err != nil {
			return nil, err
		}
	}

	return &TemplateDataObj{
		PackageName:            packageObj.PackageName,
		RootObj:                packageObj.RootObj,
		FieldObjArr:            packageObj.FieldObjArr,
		EnumObjArr:             packageObj.EnumObjArr,
		HasYAML:                packageObj.HasYAML,
		HasJSON:                packageObj.HasJSON,
		HasHJSON:               packageObj.HasHJSON,
		HasCLI:                 packageObj.HasCLI,
		HasValidate:            packageObj.HasValidate,
		HasRender:              packageObj.HasRender,
		HasPresets:             packageObj.HasPresets,
		HasInterfaces:          packageObj.HasInterfaces,
		HasSize:                packageObj.HasSize,
		HasDuration:            packageObj.HasDuration,
		HasMapAny:              packageObj.HasMapAny,
		HasTextSlice:           packageObj.HasTextSlice,
		PrimaryFormatTitle:     packageObj.PrimaryFormat,
		TypeImportTextArr:      collectTypeImports(packageObj),
		AccessorImportTextArr:  collectAccessorImports(packageObj),
		FieldMetaImportTextArr: collectFieldMetaImports(packageObj),
		RuntimeImportTextArr:   collectRuntimeImports(packageObj),
		FlagImportTextArr:      collectFlagImports(packageObj),
		ValidateImportTextArr:  collectValidateImports(packageObj),
		PresetImportTextArr:    collectPresetImports(packageObj),
		PresetObjArr:           presetObjArr,
		PresetDataArr:          presetDataArr,
	}, nil
}

func buildPresetBundle(packageObj *semantic.PackageObj) ([]PresetTemplateObj, []byte, error) {
	rawDataArr := make([]byte, 0, 4096)
	resultArr := make([]PresetTemplateObj, 0, 3)

	appendSlice := func(dataArr []byte) (int, int) {
		startVal := len(rawDataArr)
		rawDataArr = append(rawDataArr, dataArr...)
		return startVal, len(dataArr)
	}

	presetObjArr := packageObj.PresetObjArr
	if len(presetObjArr) == 0 {
		presetObjArr = []semantic.PresetObj{packageObj.FullPresetObj, packageObj.MinimalPresetObj, packageObj.MediumPresetObj}
	}

	for _, presetObj := range presetObjArr {
		itemObj := PresetTemplateObj{
			TitleText:      goName(presetObj.NameText),
			NameText:       presetObj.NameText,
			SourcePathText: presetObj.SourcePathText,
			PresentFlag:    presetObj.PresentFlag,
			FullFlag:       presetObj.GeneratedFromDefaults,
			YAMLText:       presetObj.YAMLText,
			JSONText:       presetObj.JSONText,
			HJSONText:      presetObj.HJSONText,
		}

		if presetObj.PresentFlag {
			itemObj.YAMLStart, itemObj.YAMLLen = appendSlice([]byte(presetObj.YAMLText))
			itemObj.JSONStart, itemObj.JSONLen = appendSlice([]byte(presetObj.JSONText))
			itemObj.HJSONStart, itemObj.HJSONLen = appendSlice([]byte(presetObj.HJSONText))
		}

		resultArr = append(resultArr, itemObj)
	}

	return resultArr, rawDataArr, nil
}
